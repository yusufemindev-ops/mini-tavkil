import { readFileSync, rmSync, writeFileSync, mkdirSync } from 'node:fs';
import { join } from 'node:path';

/**
 * Moves `public/admin/index.html` into `src/generated/admin-shell.ts` so only the authenticated route handler can serve the shell.
 */
const root = process.cwd();
const shellPath = join(root, 'public/admin/index.html');
const outPath = join(root, 'src/generated/admin-shell.ts');

const html = readFileSync(shellPath, 'utf8');
rmSync(shellPath);

mkdirSync(join(root, 'src/generated'), { recursive: true });
writeFileSync(
  outPath,
  `// GENERATED by scripts/bundle-admin-shell.mjs — do not edit.\n` +
    `// Run \`pnpm admin:build\` to regenerate.\n` +
    `//\n` +
    `// The admin SPA's HTML shell lives here rather than in public/ so that only\n` +
    `// the guarded route handler can serve it. See that script for why.\n` +
    `export const ADMIN_SHELL = ${JSON.stringify(html)};\n`,
);

console.log(
  `admin shell → src/generated/admin-shell.ts (${html.length} bytes, removed from public/)`,
);
