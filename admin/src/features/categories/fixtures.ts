// ── Generated bulk categories (extra parents + sub-categories for scale) ──────
// Kept compact via a builder — English complete, TR present, AR intentionally
// left incomplete on some to exercise the locale badges + fallback.

function mkCategory(
  id: string,
  parentId: string | null,
  order: number,
  status: 'draft' | 'published',
  names: { en: string; tr: string; ar?: string },
): CategorySeed {
  const slug = (s: string) =>
    s
      .toLowerCase()
      .replace(/[^a-z0-9]+/g, '-')
      .replace(/(^-|-$)/g, '');
  return {
    id,
    parentId,
    imageUrl: null,
    displayOrder: order,
    status,
    createdAt: '2026-03-01T09:00:00.000Z',
    updatedAt: '2026-05-28T09:00:00.000Z',
    translations: [
      {
        locale: 'en',
        name: names.en,
        slug: slug(names.en),
        description: `${names.en} — wholesale range.`,
        seoTitle: null,
        seoDescription: null,
        isComplete: true,
        isMachineTranslated: false,
      },
      {
        locale: 'tr',
        name: names.tr,
        slug: slug(names.tr),
        description: null,
        seoTitle: null,
        seoDescription: null,
        isComplete: true,
        isMachineTranslated: false,
      },
      {
        locale: 'ar',
        name: names.ar ?? '',
        slug: names.ar ? slug(id) + '-ar' : '',
        description: null,
        seoTitle: null,
        seoDescription: null,
        isComplete: !!names.ar,
        isMachineTranslated: !!names.ar,
      },
    ],
  };
}

