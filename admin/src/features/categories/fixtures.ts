export const CATEGORIES: AdminCategory[] = [...BASE_CATEGORIES, ...GENERATED_CATEGORIES].map(
  (c) => ({ sortStrategy: 'manual', ...c }),
);

/** Find a category by id (case-sensitive — ids are stable slugs). */
export function findCategory(id: string | undefined): AdminCategory | undefined {
  if (!id) return undefined;
  return CATEGORIES.find((c) => c.id === id);
}
